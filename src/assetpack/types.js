import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";

/**
 * Emits a declaration file exporting `AssetKey`, a union of every key the manifest resolves.
 * Consume it via the `getAsset` wrapper in `src/utils/assets.ts`.
 *
 * Must be registered *after* `pixiPipes` — pipes' `finish` hooks run in array order, and this one reads
 * the manifest the pixi-manifest pipe writes.
 *
 * @param {{ output?: string }} [options]
 * @returns {import("@assetpack/core").AssetPipe}
 */
export function types(options = {}) {
  return {
    folder: false,
    name: "types",
    defaultOptions: {
      output: "./src/assetpack/assets.d.ts",
      ...options,
    },
    test: () => true,
    finish: async (_asset, opts, pipeSystem) => {
      const manifestPipe = pipeSystem.getPipe("pixi-manifest");
      if (!manifestPipe) {
        throw new Error("assetpack types: the pixi-manifest pipe is required");
      }

      const manifestOutput = manifestPipe.defaultOptions.output;
      const manifestPath =
        dirname(manifestOutput) === "."
          ? join(pipeSystem.outputPath, manifestOutput)
          : manifestOutput;

      const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
      const entries = manifest.bundles.flatMap((bundle) => bundle.assets ?? []);

      const keys = [
        ...new Set(
          entries.flatMap((entry) => [
            ...entry.alias,
            ...(entry.data?.frameNames ?? []),
          ]),
        ),
      ].sort();

      const contents = [
        "/* eslint-disable */",
        "// AUTO-GENERATED by src/assetpack/types.js — do not edit.",
        "// Run `pnpm assetpack` to regenerate.",
        "",
        "/** Every key the manifest resolves, in every spelling. */",
        `export type AssetKey =\n${keys.map((key) => `  | ${JSON.stringify(key)}`).join("\n")};`,
        "",
      ].join("\n");

      const outputPath = resolve(opts.output);
      await mkdir(dirname(outputPath), { recursive: true });
      await writeFile(outputPath, contents, "utf8");

      console.log(
        `[assetpack] types: ${keys.length} keys -> ${relative(process.cwd(), outputPath)}`,
      );
    },
  };
}
