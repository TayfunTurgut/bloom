import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, basename, extname } from "node:path";
import { z } from "zod";
import { readFileSync } from "node:fs";

const Size = z.object({ w: z.number(), h: z.number() });
const Rect = z.object({
  x: z.number(),
  y: z.number(),
  w: z.number(),
  h: z.number(),
});

const Frame = z.object({
  frame: Rect,
  rotated: z.boolean(),
  trimmed: z.boolean(),
  spriteSourceSize: Rect,
  sourceSize: Size,
});

export const TpsSchema = z.object({
  frames: z.record(z.string(), Frame),
  animations: z.record(z.string(), z.array(z.string())),
  meta: z.object({
    app: z.string(),
    version: z.string(),
    image: z.string(),
    format: z.string(),
    size: Size,
    scale: z.number(),
    related_multi_packs: z.array(z.string()).nullable(),
  }),
});

async function addSourceFramesToSet(outputPath, path, set) {
  const source = TpsSchema.parse(
    JSON.parse(await readFile(join(outputPath, path), "utf8")),
  );
  Object.keys(source.frames).forEach((key) => set.add(key));

  if (source.meta.related_multi_packs) {
    for (const relatedMultiPack of source.meta.related_multi_packs) {
      await addSourceFramesToSet(outputPath, relatedMultiPack, set);
    }
  }
}

export function types(options = {}) {
  return {
    folder: false,
    name: "types",
    defaultOptions: {
      output: "./src/assetpack/assets.d.ts",
      ...options,
    },
    test: () => true,
    finish: async (_asset, opts, pipeSystem) => {
      const manifestPipe = pipeSystem.getPipe("pixi-manifest");
      if (!manifestPipe) {
        throw new Error("assetpack types: the pixi-manifest pipe is required");
      }

      const manifestOutput = manifestPipe.defaultOptions.output;
      const manifestPath =
        dirname(manifestOutput) === "."
          ? join(pipeSystem.outputPath, manifestOutput)
          : manifestOutput;

      const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
      const entries = manifest.bundles.flatMap((bundle) => bundle.assets ?? []);

      const keys = new Set();

      for (const entry of entries) {
        if (entry.data.tags.tps) {
          const sourcePaths = entry.src;
          for (const path of sourcePaths) {
            await addSourceFramesToSet(pipeSystem.outputPath, path, keys);
          }
        }
        entry.alias.forEach((key) => keys.add(key));
      }

      const contents = [
        "// AUTO-GENERATED by src/assetpack/types.js — do not edit.",
        "// Run `pnpm assetpack` to regenerate.",
        "",
        `export type AssetKey =\n${Array.from(keys, (key) => `  | ${JSON.stringify(key)}`).join("\n")};`,
        "",
      ].join("\n");

      const outputPath = resolve(opts.output);
      await mkdir(dirname(outputPath), { recursive: true });
      await writeFile(outputPath, contents, "utf8");

      console.log(
        `[AssetPack] types: ${keys.size} keys -> ${relative(process.cwd(), outputPath)}`,
      );
    },
  };
}
